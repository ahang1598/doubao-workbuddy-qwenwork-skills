def parse_citation(citation: str) -> Dict[str, str]:
    """
    解析法条引用
    
    支持格式:
    - 《民事诉讼法》第171条
    - 民事诉讼法第171条
    - 《民事诉讼法》第一百七十一条
    
    TODO: 完善更多解析规则
    """
    result = {"law": "", "article": "", "original": citation}
    
    # 匹配《法律名称》第X条
    pattern1 = r'《([^》]+)》第([一二三四五六七八九十\d]+)条'
    match = re.search(pattern1, citation)
    if match:
        result["law"] = match.group(1)
        result["article"] = match.group(2)
        return result
    
    # 匹配法律名称第X条
    pattern2 = r'(民事诉讼法|刑事诉讼法|行政诉讼法)第([一二三四五六七八九十\d]+)条'
    match = re.search(pattern2, citation)
    if match:
        result["law"] = match.group(1)
        result["article"] = match.group(2)
        return result
    
    return result


