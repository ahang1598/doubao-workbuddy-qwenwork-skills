def calculate_deadline_with_law(
    start_date: datetime,
    deadline_name: str,
    rule: Dict[str, Any],
    warnings: List[str]
) -> Dict[str, Any]:
    """
    计算特定期限并附加法条依据
    """
    duration = rule.get("duration", 0)
    unit = rule.get("unit", "天")
    law = rule.get("law", "")
    start_from = rule.get("start_from", "")
    
    # 计算截止日期
    if unit == "天":
        deadline_date = calculate_deadline(start_date, duration)
    elif unit == "月":
        # 简化处理：按30天/月计算
        deadline_date = start_date + timedelta(days=duration * 30)
    elif unit == "年":
        # 简化处理：按365天/年计算
        deadline_date = start_date + timedelta(days=duration * 365)
    else:
        deadline_date = start_date
    
    # 计算剩余天数
    remaining_days = (deadline_date - datetime.now()).days
    
    # 确定紧急程度
    if remaining_days < 0:
        urgency = "🔴已逾期"
    elif remaining_days <= 3:
        urgency = "🔴紧急（不足3天）"
    elif remaining_days <= 7:
        urgency = "🟠高危（3-7天）"
    elif remaining_days <= 15:
        urgency = "🟡警告（7-15天）"
    else:
        urgency = "🟢正常"
    
    return {
        "name": deadline_name,
        "duration": f"{duration}{unit}",
        "start_date": start_date.strftime("%Y-%m-%d"),
        "deadline": deadline_date.strftime("%Y-%m-%d"),
        "remaining_days": remaining_days,
        "urgency": urgency,
        "law": law,
        "law_content": LAW_CITATIONS.get(law, ""),
        "start_from": start_from,
        "notes": rule.get("note", ""),
    }


def process(payload: DateCalcInput) -> DateCalcOutput:
    """
    主处理函数 - 依据《民事诉讼法》《民法典》计算期限
    """
    warnings: List[str] = []
    deadlines: List[Dict[str, Any]] = []
    
    # 输入校验
    case_type = payload.get("case_type", "")
    case_stage = payload.get("case_stage", "")
    key_date_str = payload.get("key_date", "")
    key_date_type = payload.get("date_type", "")
    
    if not all([case_type, case_stage, key_date_str]):
        warnings.append("缺少必填参数: case_type, case_stage, key_date")
        return {
            "ok": False,
            "deadlines": deadlines,
            "warnings": warnings,
            "needs_human_review": True,
        }
    
    # 解析日期
    try:
        key_date = datetime.strptime(key_date_str, "%Y-%m-%d")
    except ValueError:
        warnings.append("日期格式错误，必须使用 YYYY-MM-DD 格式")
        return {
            "ok": False,
            "deadlines": deadlines,
            "warnings": warnings,
            "needs_human_review": True,
        }
    
    # 获取期限规则
    rules = get_deadline_rules(case_type, case_stage)
    
    if not rules:
        warnings.append(f"未找到 {case_type}/{case_stage} 的期限规则，请核实案件类型和阶段")
        return {
            "ok": False,
            "deadlines": deadlines,
            "warnings": warnings,
            "needs_human_review": True,
        }
    
    # 计算各项期限
    for deadline_name, rule_config in rules.items():
        if isinstance(rule_config, dict) and "duration" in rule_config:
            # 简单规则
            deadline_info = calculate_deadline_with_law(
                key_date, deadline_name, rule_config, warnings
            )
            deadlines.append(deadline_info)
        elif isinstance(rule_config, dict):
            # 嵌套规则（如上诉期分为判决/裁定）
            for sub_name, sub_rule in rule_config.items():
                if isinstance(sub_rule, dict) and "duration" in sub_rule:
                    full_name = f"{deadline_name}({sub_name})"
                    deadline_info = calculate_deadline_with_law(
                        key_date, full_name, sub_rule, warnings
                    )
                    deadlines.append(deadline_info)
    
    # 添加期间计算规则说明
    warnings.append("期间计算规则：")
    warnings.append(f"1. {PERIOD_CALCULATION_RULES['起算规则']}")
    warnings.append(f"2. {PERIOD_CALCULATION_RULES['节假日顺延']}")
    warnings.append(f"3. {PERIOD_CALCULATION_RULES['在途时间']}")
    warnings.append("所有计算结果仅供参考，必须以法院实际通知为准")
    
    return {
        "ok": True,
        "deadlines": deadlines,
        "warnings": warnings,
        "needs_human_review": True,  # 必须人工复核
    }


