def is_working_day(date: datetime) -> bool:
    """判断是否为工作日"""
    # 周末判断
    if date.weekday() >= 5:  # 5=周六, 6=周日
        return False
    
    # 节假日判断
    date_str = date.strftime("%Y-%m-%d")
    if date_str in HOLIDAYS_2026:
        return False
    
    return True


def get_next_working_day(date: datetime) -> datetime:
    """获取下一个工作日"""
    next_day = date + timedelta(days=1)
    while not is_working_day(next_day):
        next_day += timedelta(days=1)
    return next_day


def calculate_deadline(
    start_date: datetime,
    days: int,
    consider_holiday: bool = True
) -> datetime:
    """
    计算截止日期，处理节假日顺延
    
    TODO: 完善节假日顺延逻辑
    """
    deadline = start_date + timedelta(days=days)
    
    if consider_holiday:
        # 如果截止日是节假日，顺延至下一个工作日
        while not is_working_day(deadline):
            deadline = get_next_working_day(deadline)
    
    return deadline


